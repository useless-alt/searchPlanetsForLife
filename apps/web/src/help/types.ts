/**
 * Типы системы подсказок (задача 17; п. 11.1, 11.7; U39).
 *
 * Подсказка показывает только те блоки, для которых есть текст. Порядок
 * блоков фиксирован: what → units → why → origin. Пустые блоки не выводятся.
 */

/** Подпись блока подсказки. */
export type HelpBlockLabel = 'what' | 'units' | 'why' | 'origin';

/** Задержка показа подсказки при наведении мыши [мс] (п. 11.1). */
export const HELP_DELAY_MS = 150;

/**
 * Запись словаря терминов (п. 11.7).
 *
 * `what` — «Что это значит», `units` — единицы и привычный эквивалент,
 * `why` — «Зачем нужно» для элементов управления. `origin` не хранится в
 * словаре: он вычисляется по происхождению значения (п. 4.3, 11.1).
 */
export interface HelpEntry {
  /** Заголовок подсказки: величина или название элемента. */
  title: string;
  /** Блок «Что это значит». */
  what: string;
  /** Блок «В каких единицах и как пересчитать»; отсутствует у элементов управления. */
  units?: string;
  /** Блок «Зачем это значение» / «Зачем нужно»; отсутствует у физических величин. */
  why?: string;
}

/**
 * Контекст подсказки.
 *
 * `planetId` указывает, для какой планеты нужно взять уже рассчитанные
 * значения из кэша воркера (запросов к API нет).
 */
export interface HelpCtx {
  /** Идентификатор планеты; без него динамические блоки не выводятся. */
  planetId?: string;
}

/**
 * Расширенный контекст для 3D-слоя и карты (задача 17; п. 11.1).
 *
 * Динамические части добавляются в блоки what/why и только если они заданы.
 */
export interface HelpExtraCtx {
  /** Недостающие параметры для `stub.missing`. */
  missing?: string[];
  /** Причина недоступности переключателя (`scene.*`). */
  disabledReason?: string;
  /** Строки параметров метки для `map.label`. */
  lines?: string[];
}

/** Полный контекст подсказки: базовый и расширенный. */
export type HelpRequestCtx = HelpCtx & HelpExtraCtx;

/** Готовое содержимое подсказки. */
export interface HelpContent {
  /** Заголовок. */
  title: string;
  /**
   * Строка значения: «Значение: {число} {единица} {пояснение}».
   *
   * Само число в таблице и карточке не подменяется — пояснение только
   * дополняет его (п. 11.7).
   */
  valueLine?: string;
  /** Блоки в фиксированном порядке; пустых блоков нет. */
  blocks: Array<{ label: HelpBlockLabel; text: string }>;
  /**
   * Подпись блока `why` для элементов управления — «Зачем нужно» (U39).
   *
   * У физических величин подпись берётся из общего словаря: «Зачем это
   * значение».
   */
  whyLabel?: string;
}
