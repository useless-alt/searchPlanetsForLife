import type { HTMLAttributes } from 'react';

/**
 * Бейдж (задача 12a).
 *
 * Цвет — не единственный признак: каждый бейдж несёт текстовую метку
 * («Измерено», «Высокая», «Реконструкция по расчётной модели» и т. д.).
 * Виды бейджей: достоверность Q_data (U8), происхождение значения
 * (п. 4.3, 11.1; U15) и служебные метки карточки планеты.
 *
 * Прочие атрибуты пробрасываются на `<span>`: `ExtraOnly` помечает
 * служебный бейдж атрибутом `data-extra` (задача 18).
 */

/** Вид бейджа. */
export type BadgeKind =
  /** Достоверность Q_data: «Высокая». */
  | 'quality-high'
  /** Достоверность Q_data: «Средняя». */
  | 'quality-medium'
  /** Достоверность Q_data: «Оценочная». */
  | 'quality-low'
  /** Происхождение значения: «Измерено». */
  | 'measured'
  /** Происхождение значения: «Физика». */
  | 'physics'
  /** Происхождение значения: «Модель». */
  | 'model'
  /** Происхождение значения: «Оценка». */
  | 'estimate'
  /** «Реконструкция по расчётной модели» (Уровень Б). */
  | 'reconstructed'
  /** «Недостаточно данных для отрисовки». */
  | 'insufficient'
  /** «Низк.» — низкая достоверность параметра. */
  | 'low'
  /** «ЗО: экстраполяция» — границы зоны вне диапазона. */
  | 'extrapolated'
  /** Успешное состояние источника. */
  | 'positive'
  /** Предупреждение источника. */
  | 'warning'
  /** Ошибка источника. */
  | 'negative'
  /** Нейтральная метка без цвета. */
  | 'neutral';

/** Пропсы бейджа. */
export interface BadgeProps extends HTMLAttributes<HTMLSpanElement> {
  /** Текстовая метка (обязательна: цвет не заменяет текст). */
  label: string;
  /** Вид бейджа. */
  kind?: BadgeKind;
  /** Подсказка при наведении (например, формула режима). */
  title?: string;
  /** Дополнительный класс. */
  className?: string;
}

/** Бейдж с текстовой меткой. */
export function Badge({ label, kind = 'neutral', title, className, ...rest }: BadgeProps) {
  const classes = ['ui-badge', `ui-badge--${kind}`, className].filter(Boolean).join(' ');

  return (
    <span {...rest} className={classes} title={title}>
      {label}
    </span>
  );
}
