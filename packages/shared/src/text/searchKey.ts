/**
 * Ключ поиска по названию планеты или звезды (задача 14; п. 13.2).
 *
 * Правило нормализации: NFKD, удаление диакритики, нижний регистр и удаление
 * всей пунктуации, пробелов и символов. Буквы и цифры сохраняются в любом
 * алфавите: кириллица и греческий не удаляются и не транслитерируются.
 * Поэтому «TRAPPIST-1 d», «trappist 1d» и «TRAPPIST‑1d» дают один ключ,
 * а «Kepler-289 b» и «Kepler-289 c» — разные.
 *
 * Пустая строка остаётся пустой: поиск по ней не начинается (13.2).
 */
export function searchKey(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/\p{M}+/gu, '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, '');
}
